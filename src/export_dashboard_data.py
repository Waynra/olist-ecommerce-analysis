"""Export the dashboard aggregates (sql/dashboard.sql) to dashboard/data.js.

The dashboard is a static page, so the data ships as a small JS file instead of
being fetched; that way it also works when index.html is opened straight from disk.

Run from the project root:
    python src/export_dashboard_data.py
"""
import json
from datetime import date
from pathlib import Path

from queries import connect, load_queries, run_query

ROOT = Path(__file__).resolve().parent.parent
DASHBOARD_SQL = ROOT / "sql" / "dashboard.sql"
OUT_PATH = ROOT / "dashboard" / "data.js"


def as_table(df):
    """Columns once + rows as arrays: much smaller than a list of dicts."""
    return {"columns": list(df.columns), "rows": df.astype(object).values.tolist()}


def main():
    queries = load_queries(DASHBOARD_SQL)
    payload = {"generated": date.today().isoformat()}
    with connect() as conn:
        for name, sql in queries.items():
            df = run_query(name, conn, sql=sql)
            payload[name.removeprefix("dashboard_")] = as_table(df)
            print(f"{name}: {len(df):,} rows")
        kpis = run_query("overall_kpis", conn).iloc[0]

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(
        "// Generated by src/export_dashboard_data.py - do not edit by hand.\n"
        "window.DASHBOARD_DATA = " + json.dumps(payload, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    size_kb = OUT_PATH.stat().st_size / 1024
    print(f"\nWrote {OUT_PATH.relative_to(ROOT)} ({size_kb:,.0f} KB)")
    print(f"Check against SQL: revenue {kpis['revenue']:,.0f}, orders {int(kpis['orders']):,}, "
          f"late {kpis['late_delivery_pct']}%, review {kpis['avg_review_score']}")


if __name__ == "__main__":
    main()
